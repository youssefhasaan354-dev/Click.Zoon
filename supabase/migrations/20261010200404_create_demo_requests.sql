/*
# Create demo request storage

1. New Tables
- `demo_requests` stores visitor submissions from the free-demo form.
- `id` is a generated UUID for each request.
- `name` stores the visitor's name.
- `phone` stores the visitor's contact number.
- `business_type` stores the type of business.
- `page_url` optionally stores the business page URL.
- `created_at` records when the request was submitted.

2. Validation and integrity
- Required text fields must be non-empty and limited to 160 characters.
- Optional page URLs are limited to 500 characters and must use http or https when provided.
- A timestamp and UUID are generated by the database.

3. Security
- Row Level Security is enabled.
- Anonymous and authenticated visitors may submit a request, because the public site has no sign-in screen.
- Requests cannot be read, edited, or deleted through the public Data API. The deny policies are explicit so private contact data remains inaccessible from the browser.

4. Important notes
- The frontend can submit new requests but cannot query the stored contact information.
- Operators can review submissions through the protected database dashboard or a future authenticated admin workflow.
*/

CREATE TABLE IF NOT EXISTS public.demo_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 160),
  phone text NOT NULL CHECK (char_length(btrim(phone)) BETWEEN 5 AND 40),
  business_type text NOT NULL CHECK (char_length(btrim(business_type)) BETWEEN 1 AND 160),
  page_url text CHECK (
    page_url IS NULL
    OR (
      char_length(btrim(page_url)) BETWEEN 1 AND 500
      AND page_url ~* '^https?://'
    )
  ),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.demo_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can submit demo requests" ON public.demo_requests;
CREATE POLICY "Public can submit demo requests"
ON public.demo_requests FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Demo requests are not publicly readable" ON public.demo_requests;
CREATE POLICY "Demo requests are not publicly readable"
ON public.demo_requests FOR SELECT
TO anon, authenticated
USING (false);

DROP POLICY IF EXISTS "Demo requests cannot be publicly changed" ON public.demo_requests;
CREATE POLICY "Demo requests cannot be publicly changed"
ON public.demo_requests FOR UPDATE
TO anon, authenticated
USING (false)
WITH CHECK (false);

DROP POLICY IF EXISTS "Demo requests cannot be publicly deleted" ON public.demo_requests;
CREATE POLICY "Demo requests cannot be publicly deleted"
ON public.demo_requests FOR DELETE
TO anon, authenticated
USING (false);
